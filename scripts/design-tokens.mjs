import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

export function renderTokens(document) {
  if (document.format !== 'metritag-css-tokens-v1' || !Array.isArray(document.blocks) || !document.blocks.length) throw new Error('Unsupported token format');
  return document.blocks.map(({ selector, values }) => {
    if (!/^[\w\s\[\]='",.-]+$/.test(selector)) throw new Error(`Invalid selector ${selector}`);
    const entries = Object.entries(values);
    if (!entries.length) throw new Error('Empty token block');
    for (const [name, value] of entries) {
      if (!/^--[\w-]+$/.test(name) || typeof value !== 'string' || !value.trim() || /[;{}]/.test(value)) throw new Error(`Invalid token ${name}`);
    }
    function visit(name, path = new Set()) {
      if (path.has(name)) throw new Error(`Cyclic token ${name}`);
      const next = new Set([...path, name]);
      for (const match of values[name].matchAll(/var\((--[\w-]+)/g)) {
        if (Object.hasOwn(values, match[1])) visit(match[1], next);
      }
    }
    for (const [name] of entries) visit(name);
    return `${selector} {\n${entries.map(([name, value]) => `  ${name}: ${value};`).join('\n')}\n}`;
  }).join('\n\n') + '\n';
}

export function generate(root, check = false) {
  const header = '/* Generated by pnpm design:tokens from tokens.*.json. Edit the JSON source. */\n';
  for (const [input, output, prefix] of [
    ['tokens.core.json', 'tokens.core.css', ''],
    ['tokens.project.json', 'tokens.css', "@import './tokens.core.css';\n\n"],
  ]) {
    const source = JSON.parse(readFileSync(resolve(root, 'src/design', input), 'utf8'));
    const content = header + prefix + renderTokens(source);
    const target = resolve(root, 'src/design', output);
    if (check) {
      if (readFileSync(target, 'utf8') !== content) throw new Error(`${output} is stale. Run pnpm design:tokens`);
    } else writeFileSync(target, content);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    generate(fileURLToPath(new URL('..', import.meta.url)), process.argv.includes('--check'));
    console.log('Design token generation verified');
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
